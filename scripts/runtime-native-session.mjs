import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createServer } from "node:http";
import {
  appendFileSync,
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";

const outputDir = mkdtempSync(path.join(os.tmpdir(), "lumen-native-session-build-"));
const workspace = mkdtempSync(path.join(os.tmpdir(), "lumen-native-session-workspace-"));
const sessionRoot = mkdtempSync(path.join(os.tmpdir(), "lumen-native-session-data-"));
const outside = mkdtempSync(path.join(os.tmpdir(), "lumen-native-session-outside-"));
let server;

function sse(response, payloads) {
  response.writeHead(200, { "Content-Type": "text/event-stream" });
  for (const payload of payloads) response.write(`data: ${JSON.stringify(payload)}\n\n`);
  response.end("data: [DONE]\n\n");
}

try {
  execFileSync(
    path.join(process.cwd(), "node_modules", ".bin", "tsc"),
    [
      "src/main/agent-runtime.ts",
      "src/main/native-model-client.ts",
      "src/main/native-context.ts",
      "src/main/native-session.ts",
      "src/main/native-agent-tools.ts",
      "src/main/native-agent-runtime.ts",
      "--target", "ES2022",
      "--module", "ESNext",
      "--moduleResolution", "Bundler",
      "--outDir", outputDir,
      "--skipLibCheck",
      "--strict",
      "--esModuleInterop"
    ],
    { cwd: process.cwd(), stdio: "pipe" }
  );
  const { startNativeAgentRuntime } = await import(
    pathToFileURL(path.join(outputDir, "native-agent-runtime.js"))
  );
  const { NativeSessionStore } = await import(
    pathToFileURL(path.join(outputDir, "native-session.js"))
  );

  execFileSync("git", ["init", "-q", workspace]);
  execFileSync("git", ["-C", workspace, "config", "user.email", "test@lumen.local"]);
  execFileSync("git", ["-C", workspace, "config", "user.name", "Lumen Test"]);
  writeFileSync(path.join(workspace, "deleted-tracked.txt"), "deleted\n", "utf8");
  execFileSync("git", ["-C", workspace, "add", "deleted-tracked.txt"]);
  execFileSync("git", ["-C", workspace, "commit", "-qm", "seed"]);
  rmSync(path.join(workspace, "deleted-tracked.txt"));

  let modelCalls = 0;
  let recoveredHistory = false;
  server = createServer(async (request, response) => {
    let body = "";
    for await (const chunk of request) body += chunk;
    const parsed = JSON.parse(body);
    modelCalls += 1;
    if (modelCalls === 1) {
      sse(response, [
        { choices: [{ delta: { tool_calls: [{
          index: 0,
          id: "write-1",
          type: "function",
          function: {
            name: "Write",
            arguments: '{"file_path":"generated.txt","content":"generated by agent\\n"}'
          }
        }] } }] },
        { choices: [{ delta: {}, finish_reason: "tool_calls" }] }
      ]);
      return;
    }
    if (modelCalls === 2) {
      assert.equal(parsed.messages.at(-1).role, "tool");
      sse(response, [
        { choices: [{ delta: { content: "FIRST_DONE" } }] },
        { choices: [{ delta: {}, finish_reason: "stop" }] }
      ]);
      return;
    }
    recoveredHistory =
      parsed.messages.some((message) => message.content === "FIRST_DONE") &&
      parsed.messages.some((message) => message.content === "create a file");
    sse(response, [
      { choices: [{ delta: { content: "RECOVERED" } }] },
      { choices: [{ delta: {}, finish_reason: "stop" }] }
    ]);
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const address = server.address();
  assert(address && typeof address === "object");
  const baseUrl = `http://127.0.0.1:${address.port}/v1`;

  function start() {
    const results = [];
    const waiters = [];
    const events = [];
    const stderrs = [];
    const instance = startNativeAgentRuntime({
      prompt: "",
      persistent: true,
      cwd: workspace,
      model: "session",
      modelEndpoint: { baseUrl },
      resume: "session-recovery",
      tools: ["Write"],
      mcpServer: { command: "", args: [], env: {} },
      env: { LUMEN_NATIVE_SESSION_DIR: sessionRoot },
      permissionMode: "bypassPermissions",
      onStderr: (data) => stderrs.push(data),
      onEvent: (event) => {
        events.push(event);
        if (event.type !== "result") return;
        const waiter = waiters.shift();
        if (waiter) waiter(event);
        else results.push(event);
      }
    });
    const nextResult = () => {
      const value = results.shift();
      return value
        ? Promise.resolve(value)
        : new Promise((resolve) => waiters.push(resolve));
    };
    return { instance, events, stderrs, nextResult };
  }

  const first = start();
  first.instance.send("create a file", "checkpoint-first");
  assert.equal((await first.nextResult()).success, true);
  assert.equal(first.stderrs.some((line) => /checkpoint unavailable/i.test(line)), false);
  assert.equal(existsSync(path.join(workspace, "generated.txt")), true);
  writeFileSync(path.join(outside, "protected.txt"), "outside\n", "utf8");
  symlinkSync(path.join(outside, "protected.txt"), path.join(workspace, "unsafe-link"));

  const preview = await first.instance.rewindFiles("checkpoint-first", { dryRun: true });
  assert.equal(preview.canRewind, true);
  assert(preview.filesChanged.includes("generated.txt"));
  assert.equal(preview.skippedLinks, 1);
  assert.equal(existsSync(path.join(workspace, "generated.txt")), true);

  const rewind = await first.instance.rewindFiles("checkpoint-first");
  assert.equal(rewind.canRewind, true);
  assert.equal(existsSync(path.join(workspace, "generated.txt")), false);
  assert.equal(readFileSync(path.join(outside, "protected.txt"), "utf8"), "outside\n");
  first.instance.close();
  await first.instance.done;

  const second = start();
  second.instance.send("continue recovered session", "checkpoint-second");
  const secondResult = await second.nextResult();
  assert.equal(secondResult.success, true);
  assert.equal(secondResult.output, "RECOVERED");
  assert.equal(recoveredHistory, true);
  second.instance.close();
  await second.instance.done;

  const logPath = path.join(sessionRoot, "session-recovery", "events.jsonl");
  const eventLines = readFileSync(logPath, "utf8").trim().split("\n");
  assert(eventLines.some((line) => JSON.parse(line).type === "turn"));
  assert(eventLines.some((line) => JSON.parse(line).type === "message"));
  appendFileSync(logPath, '{"type":"message","broken":\n', "utf8");
  const recovered = await new NativeSessionStore(
    "session-recovery",
    sessionRoot
  ).loadMessages();
  assert(recovered.some((message) => message.content === "RECOVERED"));

  process.stdout.write(`${JSON.stringify({
    ok: true,
    eventLines: eventLines.length,
    recoveredMessages: recovered.length,
    rewindFiles: preview.filesChanged,
    skippedLinks: preview.skippedLinks,
    deletedTrackedSkipped: true,
    malformedTailIgnored: true,
    recoveredHistory
  })}\n`);
} finally {
  if (server) await new Promise((resolve) => server.close(resolve));
  rmSync(outputDir, { recursive: true, force: true });
  rmSync(workspace, { recursive: true, force: true });
  rmSync(sessionRoot, { recursive: true, force: true });
  rmSync(outside, { recursive: true, force: true });
}
